// Writes core/budgets.inc: the mountain budgets (subspec/mountains.md, Ridge
// placement) for every biome and season, as exact hex floats, so the
// generator looks them up instead of running the height search. Run with
// `make budgets` after any change to the mountain layouts or parameters;
// `make verify` checks the table against a fresh computation.
#include <cstdio>

#include "mountains.hpp"
#include "theme.hpp"

using namespace bh;

void print(std::FILE* f, const mountains::Budget& b) {
    std::fprintf(f, "{{");
    for (size_t i = 0; i < b.max_height.size(); ++i) std::fprintf(f, "%s%a", i ? ", " : "", b.max_height[i]);
    std::fprintf(f, "}, {");
    for (size_t i = 0; i < b.reserve.size(); ++i) std::fprintf(f, "%s%a", i ? ", " : "", b.reserve[i]);
    std::fprintf(f, "}, %a}", b.slack);
}

int main(int argc, char** argv) {
    std::FILE* f = std::fopen(argc > 1 ? argv[1] : "core/budgets.inc", "w");
    std::fprintf(f, "// Generated by tools/budgets.cpp (make budgets). Do not edit.\n");
    std::fprintf(f, "// Per theme and season, in kThemes x kSeasons order: the two- and three-ridge budgets.\n");
    for (Theme t : kThemes) {
        for (Season s : kSeasons) {
            mountains::Params p;
            p.theme = t;
            p.season = s;
            mountains::Config c = mountains::make_config(p);
            std::fprintf(f, "{");
            print(f, c.two);
            std::fprintf(f, ", ");
            print(f, c.three);
            std::fprintf(f, "},\n");
        }
    }
    std::fclose(f);
}
